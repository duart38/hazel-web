/* Writes math_tables.h, the constants behind hz_math.h, each the double nearest the exact value
 * (computed with MPFR at 256 bits). Run natively, not part of the WebAssembly build:
 *   clang -O2 -I/opt/homebrew/include math_tables.c -L/opt/homebrew/lib -lmpfr -lgmp -o /tmp/t && /tmp/t > math_tables.h */
#include <mpfr.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define PREC 256
static mpfr_t a, b, pi;

static double near(mpfr_t x) { return mpfr_get_d(x, MPFR_RNDN); }
static float float_of(uint32_t u) { float f; memcpy(&f, &u, 4); return f; }

/* x rounded to `bits` significant bits, as a double */
static double rounded(mpfr_t x, int bits) {
    mpfr_t r;
    mpfr_init2(r, bits);
    mpfr_set(r, x, MPFR_RNDN);
    double d = mpfr_get_d(r, MPFR_RNDN);
    mpfr_clear(r);
    return d;
}

int main(void) {
    mpfr_inits2(PREC, a, b, pi, (mpfr_ptr)0);
    mpfr_const_pi(pi, MPFR_RNDN);
    printf("/* Generated by math_tables.c; do not edit. */\n");

    printf("/* 2^(j/64) */\nstatic const double HZ_EXP2[64] = {\n");
    for (int j = 0; j < 64; j++) {
        mpfr_set_si(a, j, MPFR_RNDN);
        mpfr_div_si(a, a, 64, MPFR_RNDN);
        mpfr_exp2(a, a, MPFR_RNDN);
        printf("    %a,\n", near(a));
    }
    printf("};\n");

    /* log2: z in [OFF, 2 OFF) in 128 cells of equal float-bit width; invc ~ 1/centre with 29
     * significant bits, so z * invc is exact in double; logc = -log2(invc) */
    const uint32_t OFF = 0x3f330000u;
    printf("/* log2 cells: 1/centre (29 bits) and -log2 of it */\nstatic const double HZ_LOG2_INVC[128] = {\n");
    double invc[128];
    for (int i = 0; i < 128; i++) {
        double lo = float_of(OFF + ((uint32_t)i << 16)), hi = float_of(OFF + ((uint32_t)(i + 1) << 16));
        mpfr_set_d(a, (lo + hi) / 2, MPFR_RNDN);
        mpfr_ui_div(a, 1, a, MPFR_RNDN);
        invc[i] = rounded(a, 29);
        printf("    %a,\n", invc[i]);
    }
    printf("};\nstatic const double HZ_LOG2_LOGC[128] = {\n");
    for (int i = 0; i < 128; i++) {
        mpfr_set_d(a, invc[i], MPFR_RNDN);
        mpfr_log2(a, a, MPFR_RNDN);
        mpfr_neg(a, a, MPFR_RNDN);
        printf("    %a,\n", near(a));
    }
    printf("};\n");

    printf("/* atan(j/32) */\nstatic const double HZ_ATAN[33] = {\n");
    for (int j = 0; j <= 32; j++) {
        mpfr_set_si(a, j, MPFR_RNDN);
        mpfr_div_si(a, a, 32, MPFR_RNDN);
        mpfr_atan(a, a, MPFR_RNDN);
        printf("    %a,\n", near(a));
    }
    printf("};\n");

    /* cube root: m in [1, 2) in 64 cells; invc ~ 1/centre with 29 significant bits, so m * invc is
     * exact, and cbrt(2^s / invc) for s = 0, 1, 2 */
    printf("/* cube root cells: 1/centre (29 bits), and cbrt(2^s / that) */\nstatic const double HZ_CBRT_INVC[64] = {\n");
    double cinv[64];
    for (int i = 0; i < 64; i++) {
        mpfr_set_d(a, 1.0 + (i + 0.5) / 64.0, MPFR_RNDN);
        mpfr_ui_div(a, 1, a, MPFR_RNDN);
        cinv[i] = rounded(a, 29);
        printf("    %a,\n", cinv[i]);
    }
    printf("};\nstatic const double HZ_CBRT[3][64] = {\n");
    for (int s = 0; s < 3; s++) {
        printf("    {\n");
        for (int i = 0; i < 64; i++) {
            mpfr_set_d(a, cinv[i], MPFR_RNDN);
            mpfr_ui_div(a, 1u << s, a, MPFR_RNDN);
            mpfr_cbrt(a, a, MPFR_RNDN);
            printf("        %a,\n", near(a));
        }
        printf("    },\n");
    }
    printf("};\n");

    /* pi/2 in three parts: 38 + 38 + 53 bits, so k * part is exact for |k| < 2^15 */
    mpfr_div_si(a, pi, 2, MPFR_RNDN);
    double p1 = rounded(a, 38);
    mpfr_sub_d(a, a, p1, MPFR_RNDN);
    double p2 = rounded(a, 38);
    mpfr_sub_d(a, a, p2, MPFR_RNDN);
    double p3 = near(a);
    printf("#define HZ_PIO2_1 %a\n#define HZ_PIO2_2 %a\n#define HZ_PIO2_3 %a\n", p1, p2, p3);
    mpfr_div_si(a, pi, 2, MPFR_RNDN);
    printf("#define HZ_PI_2 %a\n", near(a));
    printf("#define HZ_PI %a\n", near(pi));
    mpfr_set_si(a, 2, MPFR_RNDN);
    mpfr_div(a, a, pi, MPFR_RNDN);
    printf("#define HZ_2_PI %a\n", near(a));
    mpfr_const_log2(a, MPFR_RNDN);
    printf("#define HZ_LN2 %a\n", near(a));
    mpfr_ui_div(b, 1, a, MPFR_RNDN);
    printf("#define HZ_INV_LN2 %a\n", near(b));  /* also log2(e) */
    mpfr_clears(a, b, pi, (mpfr_ptr)0);
    return 0;
}
